function pick(options, previous, random) {
  const fresh = options.filter(option => option[1] !== previous?.text);
  const pool = fresh.length ? fresh : options;
  const [label, text, theme] = pool[Math.floor(random() * pool.length)];
  return { label, text, theme };
}

export function rollIdea({ mode, selected, topic, current = [], slots = [0, 1, 2] }, random = Math.random) {
  const choices = selected.length ? selected : Object.keys(themes);
  const subjects = [];
  for (const key of choices) {
    if (key === 'custom') {
      subjects.push(...freeTopics[mode].map(([label, text]) => [
        label + ' · ' + topic, text.replace('{topic}', () => topic), key
      ]));
    } else {
      subjects.push(...themes[key][mode].map(([label, text]) => [label, text, key]));
    }
  }

  const next = [...current];
  if (slots.includes(0)) next[0] = pick(subjects, current[0], random);
  if (slots.includes(1)) next[1] = pick(twists[mode], current[1], random);

  if (slots.includes(2)) {
    const partner = selected.find(key => key !== next[0].theme);
    let options = finishes;
    if (partner === 'custom') {
      options = freeAccents.map(([label, text]) => [label + ' · ' + topic, text.replace('{topic}', () => topic)]);
    } else if (partner) {
      options = themes[partner].accents;
    } else if (selected.length === 1 && next[0].theme !== 'custom') {
      options = [...themes[next[0].theme].accents, ...finishes];
    }
    next[2] = pick(options, current[2], random);
  }
  return next;
}

